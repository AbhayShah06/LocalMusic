package com.abhayshah.localmusic;

import android.content.Context;
import android.util.Base64;
import org.json.JSONArray;
import org.json.JSONObject;
import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.InputStream;
import java.net.HttpURLConnection;
import java.net.URL;
import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.HashSet;
import java.util.Set;

/** Fetches lyrics on demand and keeps successful results on this phone. */
final class LyricsClient {
    static String get(Context context, Track track) {
        File directory = new File(context.getCacheDir(), "lyrics"), cached = new File(directory, digest(track.stableId) + ".txt");
        String local = read(cached); if (!local.isEmpty()) return local;
        try {
            String cleanTitle = cleanTitle(track.title), cleanArtist = track.artist.replaceAll("(?i)\\s*-\\s*topic$", "").trim();
            String best = lrclib(cleanTitle, cleanArtist);
            if (best.isEmpty()) best = lrclib(cleanTitle, "");
            if (best.isEmpty() && track.stableId.startsWith("online:")) best = captions(track);
            if (!best.isEmpty()) { if (!directory.exists()) directory.mkdirs(); try (FileOutputStream output = new FileOutputStream(cached)) { output.write(best.getBytes(StandardCharsets.UTF_8)); } }
            return best;
        } catch (Exception ignored) { return ""; }
    }

    private static String lrclib(String title, String artist) {
        try {
            String query = "track_name=" + encode(title) + (artist.isEmpty() ? "" : "&artist_name=" + encode(artist));
            String body = fetch("https://lrclib.net/api/search?" + query); if (body.isEmpty()) return "";
            JSONArray results = new JSONArray(body);
            for (int i = 0; i < Math.min(12, results.length()); i++) { String plain = results.getJSONObject(i).optString("plainLyrics", "").trim(); if (!plain.isEmpty()) return plain; }
        } catch (Exception ignored) { }
        return "";
    }

    private static String captions(Track track) {
        try {
            new OnlineCatalogSource(); String[] pieces = track.stableId.split(":", 3); int service = Integer.parseInt(pieces[1]);
            String page = new String(Base64.decode(pieces[2], Base64.URL_SAFE), StandardCharsets.UTF_8);
            org.schabi.newpipe.extractor.stream.StreamInfo info = org.schabi.newpipe.extractor.stream.StreamInfo.getInfo(org.schabi.newpipe.extractor.NewPipe.getService(service), page);
            java.util.List<org.schabi.newpipe.extractor.stream.SubtitlesStream> subtitles = new java.util.ArrayList<>(info.getSubtitles());
            subtitles.sort((a, b) -> Integer.compare(captionScore(b), captionScore(a)));
            for (org.schabi.newpipe.extractor.stream.SubtitlesStream subtitle : subtitles) {
                String raw = subtitle.isUrl() ? fetch(subtitle.getUrl()) : subtitle.getContent(); String plain = plainCaptions(raw);
                if (plain.length() >= 80) return plain;
            }
        } catch (Exception ignored) { }
        return "";
    }

    private static int captionScore(org.schabi.newpipe.extractor.stream.SubtitlesStream stream) {
        String language = (stream.getLanguageTag() + " " + stream.getDisplayLanguageName()).toLowerCase(java.util.Locale.ROOT);
        return (stream.isAutoGenerated() ? 0 : 30) + (language.contains("en") || language.contains("english") ? 20 : 0) + (language.contains("hi") || language.contains("hindi") ? 10 : 0);
    }

    private static String plainCaptions(String raw) {
        if (raw == null || raw.isEmpty()) return "";
        if (raw.trim().startsWith("{")) try {
            JSONObject root = new JSONObject(raw); JSONArray events = root.optJSONArray("events"); StringBuilder text = new StringBuilder(); String previous = "";
            if (events != null) for (int i = 0; i < events.length(); i++) { JSONArray segs = events.getJSONObject(i).optJSONArray("segs"); if (segs == null) continue; StringBuilder line = new StringBuilder(); for (int j = 0; j < segs.length(); j++) line.append(segs.getJSONObject(j).optString("utf8")); String clean = line.toString().replace("\\n", " ").trim(); if (!clean.isEmpty() && !clean.equals(previous)) { text.append(clean).append('\n'); previous = clean; } } return text.toString().trim();
        } catch (Exception ignored) { }
        String normalized = raw.replaceAll("(?s)<[^>]+>", " ").replace("&amp;", "&").replace("&quot;", "\"").replace("&#39;", "'");
        StringBuilder out = new StringBuilder(); Set<String> recent = new HashSet<>();
        for (String line : normalized.split("\\R")) { String clean = line.replaceAll("<[^>]+>", "").replaceAll("^\\d+$", "").trim(); if (clean.isEmpty() || clean.equals("WEBVTT") || clean.contains("-->")) continue; if (recent.add(clean)) out.append(clean).append('\n'); if (recent.size() > 80) recent.clear(); }
        return out.toString().trim();
    }

    static String cleanTitle(String value) {
        return value.replaceAll("\\([^)]*\\)|\\[[^]]*]", " ").replaceAll("(?i)official|music video|video|audio|lyrics?|english translation|translation|full version|hd|4k|with|and", " ").replaceAll("\\s+", " ").trim();
    }

    private static String fetch(String url) {
        HttpURLConnection connection = null; try { connection = (HttpURLConnection)new URL(url).openConnection(); connection.setConnectTimeout(8_000); connection.setReadTimeout(14_000); connection.setRequestProperty("User-Agent", "LocalMusic/0.10 Android"); if (connection.getResponseCode() / 100 != 2) return ""; try (InputStream input = connection.getInputStream(); ByteArrayOutputStream output = new ByteArrayOutputStream()) { byte[] buffer = new byte[8192]; for (int n; (n = input.read(buffer)) > 0; ) output.write(buffer, 0, n); return output.toString(StandardCharsets.UTF_8.name()); } } catch (Exception ignored) { return ""; } finally { if (connection != null) connection.disconnect(); }
    }
    private static String encode(String value) throws Exception { return URLEncoder.encode(value, StandardCharsets.UTF_8.name()); }
    private static String read(File file) { if (!file.isFile()) return ""; try (FileInputStream input = new FileInputStream(file); ByteArrayOutputStream output = new ByteArrayOutputStream()) { byte[] buffer = new byte[8192]; for (int n; (n = input.read(buffer)) > 0; ) output.write(buffer, 0, n); return output.toString(StandardCharsets.UTF_8.name()); } catch (Exception ignored) { return ""; } }
    private static String digest(String value) { try { byte[] bytes = MessageDigest.getInstance("SHA-256").digest(value.getBytes(StandardCharsets.UTF_8)); StringBuilder out = new StringBuilder(); for (byte b : bytes) out.append(String.format(java.util.Locale.ROOT, "%02x", b)); return out.toString(); } catch (Exception ignored) { return Integer.toHexString(value.hashCode()); } }
    static void clear(Context context) { File[] files = new File(context.getCacheDir(), "lyrics").listFiles(); if (files != null) for (File file : files) file.delete(); }
    private LyricsClient() { }
}
